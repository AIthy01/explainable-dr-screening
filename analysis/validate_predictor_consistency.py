import os
import sys

import numpy as np
import pandas as pd
import torch

from torch.utils.data import DataLoader, Subset
from sklearn.model_selection import train_test_split
from sklearn.metrics import (
    accuracy_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
)

from dataset import DRDataset
from transforms import get_val_transform
from predictor import DRPredictor
from config import (
    TRAIN_CSV,
    IMAGE_DIR,
    BATCH_SIZE,
    NUM_WORKERS,
)


# ============================================================
# Configuration
# ============================================================

PRED_DIR = "results/predictions"

ATOL = 1e-5
RTOL = 1e-5


# ============================================================
# Reconstruct exactly the same validation split
# ============================================================

df = pd.read_csv(TRAIN_CSV)

_, val_idx = train_test_split(
    np.arange(len(df)),
    test_size=0.2,
    random_state=42,
    stratify=df["diagnosis"],
)

dataset = Subset(
    DRDataset(
        TRAIN_CSV,
        IMAGE_DIR,
        get_val_transform(),
    ),
    val_idx,
)

loader = DataLoader(
    dataset,
    batch_size=BATCH_SIZE,
    shuffle=False,
    num_workers=NUM_WORKERS,
    pin_memory=torch.cuda.is_available(),
)


# ============================================================
# Load final predictor
# ============================================================

predictor = DRPredictor()

device = predictor.device

vgg = predictor.models["vgg16"]["model"]
resnet = predictor.models["resnet50"]["model"]

w_vgg = predictor.models["vgg16"]["weight"]
w_resnet = predictor.models["resnet50"]["weight"]

print()
print("=" * 90)
print("PREDICTOR CONSISTENCY VALIDATION")
print("=" * 90)
print(f"Validation samples : {len(dataset)}")
print(f"Batch size         : {BATCH_SIZE}")
print(f"Device             : {device}")
print(
    f"Fusion weights     : "
    f"VGG16={w_vgg:.2f}, "
    f"ResNet50={w_resnet:.2f}"
)
print(
    f"Referral threshold : "
    f"{predictor.referral_threshold:.2f}"
)


# ============================================================
# Re-run inference using the models owned by DRPredictor
# ============================================================

new_labels = []
new_vgg_probs = []
new_resnet_probs = []

with torch.inference_mode():

    for images, targets in loader:

        images = images.to(
            device,
            non_blocking=True,
        )

        vgg_logits = vgg(images)
        resnet_logits = resnet(images)

        vgg_probs = torch.softmax(
            vgg_logits,
            dim=1,
        )

        resnet_probs = torch.softmax(
            resnet_logits,
            dim=1,
        )

        new_labels.append(
            targets.numpy()
        )

        new_vgg_probs.append(
            vgg_probs.cpu().numpy()
        )

        new_resnet_probs.append(
            resnet_probs.cpu().numpy()
        )


new_labels = np.concatenate(
    new_labels,
    axis=0,
)

new_vgg_probs = np.concatenate(
    new_vgg_probs,
    axis=0,
)

new_resnet_probs = np.concatenate(
    new_resnet_probs,
    axis=0,
)


# ============================================================
# Load reference arrays generated by evaluate.py
# ============================================================

saved_labels = np.load(
    os.path.join(
        PRED_DIR,
        "labels.npy",
    )
)

saved_vgg_probs = np.load(
    os.path.join(
        PRED_DIR,
        "vgg16_probs.npy",
    )
)

saved_resnet_probs = np.load(
    os.path.join(
        PRED_DIR,
        "resnet50_probs.npy",
    )
)


# ============================================================
# Basic shape/order checks
# ============================================================

print()
print("=" * 90)
print("1. DATA / ORDER CHECK")
print("=" * 90)

print(
    f"New labels shape   : "
    f"{new_labels.shape}"
)

print(
    f"Saved labels shape : "
    f"{saved_labels.shape}"
)

labels_identical = np.array_equal(
    new_labels,
    saved_labels,
)

print(
    f"Labels identical   : "
    f"{labels_identical}"
)


# ============================================================
# Probability consistency
# ============================================================

vgg_max_diff = np.max(
    np.abs(
        new_vgg_probs
        - saved_vgg_probs
    )
)

resnet_max_diff = np.max(
    np.abs(
        new_resnet_probs
        - saved_resnet_probs
    )
)

vgg_allclose = np.allclose(
    new_vgg_probs,
    saved_vgg_probs,
    atol=ATOL,
    rtol=RTOL,
)

resnet_allclose = np.allclose(
    new_resnet_probs,
    saved_resnet_probs,
    atol=ATOL,
    rtol=RTOL,
)

vgg_pred_equal = np.array_equal(
    np.argmax(new_vgg_probs, axis=1),
    np.argmax(saved_vgg_probs, axis=1),
)

resnet_pred_equal = np.array_equal(
    np.argmax(new_resnet_probs, axis=1),
    np.argmax(saved_resnet_probs, axis=1),
)


print()
print("=" * 90)
print("2. INDIVIDUAL MODEL CONSISTENCY")
print("=" * 90)

print("VGG16")
print(
    f"  max abs probability difference : "
    f"{vgg_max_diff:.10e}"
)
print(
    f"  probabilities allclose         : "
    f"{vgg_allclose}"
)
print(
    f"  predictions identical          : "
    f"{vgg_pred_equal}"
)

print()

print("ResNet50")
print(
    f"  max abs probability difference : "
    f"{resnet_max_diff:.10e}"
)
print(
    f"  probabilities allclose         : "
    f"{resnet_allclose}"
)
print(
    f"  predictions identical          : "
    f"{resnet_pred_equal}"
)


# ============================================================
# Ensemble consistency
# ============================================================

new_fused_probs = (
    w_vgg * new_vgg_probs
    + w_resnet * new_resnet_probs
)

saved_fused_probs = (
    w_vgg * saved_vgg_probs
    + w_resnet * saved_resnet_probs
)

fused_max_diff = np.max(
    np.abs(
        new_fused_probs
        - saved_fused_probs
    )
)

fused_allclose = np.allclose(
    new_fused_probs,
    saved_fused_probs,
    atol=ATOL,
    rtol=RTOL,
)

new_preds = np.argmax(
    new_fused_probs,
    axis=1,
)

saved_preds = np.argmax(
    saved_fused_probs,
    axis=1,
)

fused_pred_equal = np.array_equal(
    new_preds,
    saved_preds,
)

print()
print("=" * 90)
print("3. ENSEMBLE CONSISTENCY")
print("=" * 90)

print(
    f"Max abs probability difference : "
    f"{fused_max_diff:.10e}"
)

print(
    f"Probabilities allclose         : "
    f"{fused_allclose}"
)

print(
    f"Predictions identical          : "
    f"{fused_pred_equal}"
)


# ============================================================
# Five-class metrics
# ============================================================

accuracy = accuracy_score(
    new_labels,
    new_preds,
)

macro_f1 = f1_score(
    new_labels,
    new_preds,
    average="macro",
    zero_division=0,
)

multiclass_auc = roc_auc_score(
    new_labels,
    new_fused_probs,
    multi_class="ovr",
    average="macro",
)


print()
print("=" * 90)
print("4. FINAL FIVE-CLASS ENSEMBLE PERFORMANCE")
print("=" * 90)

print(
    f"Accuracy    : {accuracy:.4f}"
)

print(
    f"Macro-F1    : {macro_f1:.4f}"
)

print(
    f"Macro AUC   : {multiclass_auc:.4f}"
)


# ============================================================
# Referable DR score-based decision
# ============================================================

ref_score = new_fused_probs[
    :,
    2:
].sum(axis=1)

y_true_ref = (
    new_labels >= 2
).astype(int)

y_pred_ref = (
    ref_score
    >= predictor.referral_threshold
).astype(int)

tn, fp, fn, tp = confusion_matrix(
    y_true_ref,
    y_pred_ref,
    labels=[0, 1],
).ravel()

ref_recall = (
    tp / (tp + fn)
    if (tp + fn) > 0
    else 0.0
)

ref_specificity = (
    tn / (tn + fp)
    if (tn + fp) > 0
    else 0.0
)

ref_precision = (
    tp / (tp + fp)
    if (tp + fp) > 0
    else 0.0
)

ref_npv = (
    tn / (tn + fn)
    if (tn + fn) > 0
    else 0.0
)

ref_f1 = (
    2 * ref_precision * ref_recall
    / (ref_precision + ref_recall)
    if (ref_precision + ref_recall) > 0
    else 0.0
)

ref_auc = roc_auc_score(
    y_true_ref,
    ref_score,
)


print()
print("=" * 90)
print("5. REFERABLE DR SCORE PERFORMANCE")
print("=" * 90)

print(
    f"Threshold   : "
    f"{predictor.referral_threshold:.2f}"
)

print(
    f"ROC-AUC     : {ref_auc:.4f}"
)

print(
    f"Recall      : {ref_recall:.4f}"
)

print(
    f"Specificity : {ref_specificity:.4f}"
)

print(
    f"Precision   : {ref_precision:.4f}"
)

print(
    f"NPV         : {ref_npv:.4f}"
)

print(
    f"F1          : {ref_f1:.4f}"
)

print(
    f"TP / FP     : {tp} / {fp}"
)

print(
    f"FN / TN     : {fn} / {tn}"
)


# ============================================================
# Final PASS / FAIL
# ============================================================

checks = {
    "labels_identical":
        labels_identical,

    "vgg_probs_allclose":
        vgg_allclose,

    "resnet_probs_allclose":
        resnet_allclose,

    "vgg_predictions_identical":
        vgg_pred_equal,

    "resnet_predictions_identical":
        resnet_pred_equal,

    "ensemble_probs_allclose":
        fused_allclose,

    "ensemble_predictions_identical":
        fused_pred_equal,
}

print()
print("=" * 90)
print("6. FINAL CONSISTENCY CHECK")
print("=" * 90)

for name, passed in checks.items():

    status = (
        "PASS"
        if passed
        else "FAIL"
    )

    print(
        f"{name:<35} : {status}"
    )


all_passed = all(
    checks.values()
)

print()

if all_passed:

    print(
        "FINAL RESULT: PASS"
    )

    print(
        "Research evaluation pipeline and "
        "DRPredictor inference pipeline are consistent."
    )

else:

    print(
        "FINAL RESULT: FAIL"
    )

    print(
        "Do NOT proceed to Grad-CAM / deployment "
        "until the mismatch is investigated."
    )

    sys.exit(1)
